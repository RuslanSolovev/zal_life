Future<Map<String, Map<String, dynamic>>> _loadProductMap(DatabaseExecutor db) async {
  final rows = await db.query('food_products');
  final map = <String, Map<String, dynamic>>{};
  for (final row in rows) {
    final normalized = (row['nameNormalized'] as String?)?.trim() ?? _normalizeName(row['name'] as String? ?? '');
    if (normalized.isEmpty) continue;
    map[normalized] = {
      'id': row['id'] as String,
      'name': row['name'] as String,
      'calories': (row['calories'] as num?)?.toDouble() ?? 0,
      'protein': (row['protein'] as num?)?.toDouble() ?? 0,
      'fat': (row['fat'] as num?)?.toDouble() ?? 0,
      'carbs': (row['carbs'] as num?)?.toDouble() ?? 0,
      'fiber': (row['fiber'] as num?)?.toDouble() ?? 0,
    };
  }
  return map;
}

List<Map<String, dynamic>>? _parseTemplateIngredients(
    Map<String, Map<String, dynamic>> products,
    String rawIngredients,
    String templateName,
    ) {
  final parts = rawIngredients.split(';').map((part) => part.trim()).where((part) => part.isNotEmpty);
  final items = <Map<String, dynamic>>[];

  for (final part in parts) {
    final separator = part.lastIndexOf(':');
    if (separator <= 0) { debugPrint('⚠️ Некорректный ингредиент "$part" в "$templateName"'); return null; }

    final productName = part.substring(0, separator).trim();
    final grams = double.tryParse(part.substring(separator + 1).trim());

    if (grams == null || grams <= 0) { debugPrint('⚠️ Некорректный вес "$part" в "$templateName"'); return null; }

    final product = products[_normalizeName(productName)];
    if (product == null) { debugPrint('⚠️ Продукт "$productName" не найден в "$templateName"'); return null; }

    items.add({'productId': product['id'], 'grams': grams, 'name': product['name']});
  }
  return items;
}